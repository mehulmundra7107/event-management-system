-- ============================================================
-- coep_sample_data.sql
-- Event Management System - COEP Tech, Pune sample data
--
-- HOW TO RUN (MySQL 8.0.16+ recommended, CHECK constraint needs it):
--   mysql -u root -p < coep_sample_data.sql
--   or open it in MySQL Workbench and run the whole script.
--
-- This script is SAFE TO RE-RUN. It will:
--   1. create the database + tables if they do not exist (same as schema.sql)
--   2. empty all tables
--   3. insert fresh sample data
--
-- All event / registration / feedback dates are RELATIVE to CURDATE(),
-- so the derived status (Completed / Ongoing / Upcoming) stays correct
-- no matter which day you run it. Re-run it to refresh the dates.
-- ============================================================

SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS event_management CHARACTER SET utf8mb4;
USE event_management;

CREATE TABLE IF NOT EXISTS student (
    student_id  INT AUTO_INCREMENT PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE,
    department  VARCHAR(100) NOT NULL,
    year        INT NOT NULL
);
CREATE TABLE IF NOT EXISTS student_phone (
    phone_id    INT AUTO_INCREMENT PRIMARY KEY,
    student_id  INT NOT NULL,
    phone       VARCHAR(20) NOT NULL,
    FOREIGN KEY (student_id) REFERENCES student(student_id)
);
CREATE TABLE IF NOT EXISTS club (
    club_id       INT AUTO_INCREMENT PRIMARY KEY,
    club_name     VARCHAR(150) NOT NULL,
    description   TEXT,
    contact_email VARCHAR(150)
);
CREATE TABLE IF NOT EXISTS organizer (
    organizer_id    INT AUTO_INCREMENT PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    email           VARCHAR(150) NOT NULL UNIQUE,
    department_club VARCHAR(150)
);
CREATE TABLE IF NOT EXISTS organizer_phone (
    phone_id     INT AUTO_INCREMENT PRIMARY KEY,
    organizer_id INT NOT NULL,
    phone        VARCHAR(20) NOT NULL,
    FOREIGN KEY (organizer_id) REFERENCES organizer(organizer_id)
);
CREATE TABLE IF NOT EXISTS venue (
    venue_id    INT AUTO_INCREMENT PRIMARY KEY,
    venue_name  VARCHAR(150) NOT NULL,
    location    VARCHAR(255),
    capacity    INT NOT NULL
);
CREATE TABLE IF NOT EXISTS event_category (
    category_id   INT AUTO_INCREMENT PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL,
    description   TEXT
);
CREATE TABLE IF NOT EXISTS event (
    event_id      INT AUTO_INCREMENT PRIMARY KEY,
    event_name    VARCHAR(200) NOT NULL,
    description   TEXT,
    event_date    DATE NOT NULL,
    event_type    VARCHAR(100),
    start_time    TIME,
    end_time      TIME,
    club_id       INT NOT NULL,
    organizer_id  INT NOT NULL,
    venue_id      INT NOT NULL,
    category_id   INT NOT NULL,
    FOREIGN KEY (club_id)      REFERENCES club(club_id),
    FOREIGN KEY (organizer_id) REFERENCES organizer(organizer_id),
    FOREIGN KEY (venue_id)     REFERENCES venue(venue_id),
    FOREIGN KEY (category_id)  REFERENCES event_category(category_id)
);
CREATE TABLE IF NOT EXISTS event_schedule (
    event_id      INT NOT NULL,
    schedule_id   INT NOT NULL,
    activity_name VARCHAR(200) NOT NULL,
    start_time    TIME,
    end_time      TIME,
    PRIMARY KEY (event_id, schedule_id),
    FOREIGN KEY (event_id) REFERENCES event(event_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS registration (
    registration_id   INT AUTO_INCREMENT PRIMARY KEY,
    student_id        INT NOT NULL,
    event_id          INT NOT NULL,
    registration_date DATE NOT NULL,
    status            VARCHAR(50) DEFAULT 'Registered',
    UNIQUE (student_id, event_id),
    FOREIGN KEY (student_id) REFERENCES student(student_id),
    FOREIGN KEY (event_id)   REFERENCES event(event_id)
);
CREATE TABLE IF NOT EXISTS feedback (
    feedback_id   INT AUTO_INCREMENT PRIMARY KEY,
    student_id    INT NOT NULL,
    event_id      INT NOT NULL,
    rating        INT NOT NULL,
    comments      TEXT,
    feedback_date DATE NOT NULL,
    FOREIGN KEY (student_id) REFERENCES student(student_id),
    FOREIGN KEY (event_id)   REFERENCES event(event_id),
    CHECK (rating BETWEEN 1 AND 5)
);

-- ------------------------------------------------------------
-- Clear existing data (children first is not needed because
-- FK checks are switched off while truncating; AUTO_INCREMENT resets to 1)
-- ------------------------------------------------------------
SET FOREIGN_KEY_CHECKS = 0;
TRUNCATE TABLE feedback;
TRUNCATE TABLE registration;
TRUNCATE TABLE event_schedule;
TRUNCATE TABLE event;
TRUNCATE TABLE organizer_phone;
TRUNCATE TABLE student_phone;
TRUNCATE TABLE student;
TRUNCATE TABLE organizer;
TRUNCATE TABLE club;
TRUNCATE TABLE venue;
TRUNCATE TABLE event_category;
SET FOREIGN_KEY_CHECKS = 1;


